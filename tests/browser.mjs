import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[],events=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route('**/rest/v1/rpc/pnu_collect',async route=>{events.push(...route.request().postDataJSON().batch);await route.fulfill({status:204,body:''});});
await page.goto('http://127.0.0.1:4173/?utm_source=instagram');
await page.getByRole('heading',{name:/낮의 캠퍼스는 잊어/}).waitFor();
assert.equal(events.length,0);
await page.locator('#accept').click();
await page.locator('#start').click();
await page.locator('dialog').waitFor({state:'visible'});
await page.locator('dialog input[type=checkbox]').check();
await page.locator('dialog button[type=submit]').click();
await page.getByRole('status').filter({hasText:'체험 신청이 완료'}).waitFor();
await page.waitForTimeout(200);
await page.evaluate(async()=>{const a=await import('./analytics.js');await a.flush();});
for(const name of ['page_view','ticket_view','checkout_start','demo_complete'])assert.ok(events.some(e=>e.event_name===name),name);
assert.ok(events.every(e=>e.event_name!=='purchase'));
await page.locator('#close').click();
await mkdir('test-results',{recursive:true});
await page.screenshot({path:'test-results/desktop.png',fullPage:true});
await page.locator('#privacy').click();await page.locator('#decline').click();
const before=events.length;await page.locator('[data-track=hero_program]').click();await page.waitForTimeout(100);assert.equal(events.length,before);
await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:4173/');
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:'test-results/mobile.png',fullPage:true});
await page.goto('http://127.0.0.1:4173/admin.html');
await page.locator('#metrics .metric').first().waitFor();assert.equal(await page.locator('#metrics .metric').count(),4);
await page.locator('#mode').selectOption('live');await page.getByRole('status').filter({hasText:'로그인하세요'}).waitFor();
assert.equal(await page.locator('#metrics .metric').count(),0);
assert.deepEqual(errors,[]);
await browser.close();console.log('Browser passed: consent, funnel, demo flow, refusal, mobile overflow, dashboard access.');
